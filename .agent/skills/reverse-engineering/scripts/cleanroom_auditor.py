#!/usr/bin/env python3
"""
Tersine Mühendislik ve Temiz Oda (Clean-Room) Doğrulayıcı - Antigravity AI-OS
=============================================================================

43. Kural ve reverse-engineering becerisi uyarınca:
1. Kaynak kodda şüpheli decompiler kalıntılarını (Ghidra/IDA/JADX header'ları, raw hex dumps) tarar.
2. Telif hakkı ve lisans ihlali yaratabilecek ham decompiled kod yapıştırmalarını tespit eder.
3. Clean-room yeniden yazım disiplinine uygunluğu ve delil raporu varlığını doğrular.

Kullanım:
    python .agent/skills/reverse-engineering/scripts/cleanroom_auditor.py <hedef_dizin>
"""

import os
import sys
import re
from pathlib import Path

# ANSI Renk Kodları
GREEN = '\033[92m'
YELLOW = '\033[93m'
RED = '\033[91m'
CYAN = '\033[96m'
ENDC = '\033[0m'

SUSPICIOUS_SIGNATURES = [
    (r"Generated by Ghidra", "Ghidra decompiler imzası tespit edildi. Ham kod kopyalamak yerine clean-room rewrite yapılmalıdır."),
    (r"Decompiled with CFR", "CFR decompiler imzası tespit edildi."),
    (r"This file was decompiled by JADX", "JADX decompiler başlığı tespit edildi."),
    (r"Decompiled with Fernflower", "Fernflower decompiler başlığı tespit edildi."),
    (r"// <auto-generated>.*ILSpy", "ILSpy otomatik üretim başlığı tespit edildi."),
    (r"ida_pro|ida64", "IDA Pro ham log veya decompile artığı tespit edildi."),
    (r"__asm__\s*\(", "Doğrudan ham inline assembly kopyalama şüphesi.")
]

IGNORE_DIRS = {
    ".git", "node_modules", "dist", "build", "target",
    ".gemini", ".next", "venv", "__pycache__",
    "awesome-reverse-engineer-anything-main"
}

IGNORE_FILES = {
    "cleanroom_auditor.py"
}

def audit_directory(target_path: Path):
    print(f"\n{CYAN}🔬 [43. Kural] Temiz Oda ve Tersine Mühendislik Denetimi Başlatılıyor...{ENDC}")
    print(f"Hedef Dizin: {target_path.resolve()}\n")

    issues = []
    total_files = 0

    for root, dirs, files in os.walk(target_path):
        dirs[:] = [d for d in dirs if d not in IGNORE_DIRS]

        for file in files:
            if file in IGNORE_FILES:
                continue
            file_path = Path(root) / file
            # Yalnızca kod veya metin dosyalarını incele
            if file_path.suffix.lower() in {'.js', '.ts', '.jsx', '.tsx', '.py', '.rs', '.go', '.java', '.cs', '.cpp', '.c', '.md'}:
                total_files += 1
                try:
                    content = file_path.read_text(encoding="utf-8", errors="ignore")
                    for pattern, message in SUSPICIOUS_SIGNATURES:
                        if re.search(pattern, content, re.IGNORECASE):
                            issues.append((str(file_path.relative_to(target_path)), message))
                except Exception:
                    pass

    print(f"İncelenen dosya sayısı: {total_files}")

    if not issues:
        print(f"\n{GREEN}✅ Temiz Oda Denetimi Başarılı! Telifli decompiler artığı veya şüpheli ham kod tespit edilmedi.{ENDC}\n")
        return 0
    else:
        print(f"\n{RED}❌ Dikkat: Şüpheli Decompiler veya Tersine Mühendislik İhlali Bulundu ({len(issues)} adet):{ENDC}")
        for filepath, msg in issues:
            print(f"  - {YELLOW}{filepath}{ENDC}: {msg}")
        print(f"\n{YELLOW}💡 Tavsiye: 43. kural gereğince decompiler çıktıları doğrudan projeye eklenemez. Yalnızca spesifikasyon çıkarılıp sıfırdan clean-room yazılmalıdır.{ENDC}\n")
        return 1

if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    sys.exit(audit_directory(target))
